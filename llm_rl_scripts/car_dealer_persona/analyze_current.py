"""Analyzer for CD-PERSONA-1 (``PREREGISTRATION_CURRENT.md``): the current-model arms.

`analyze.py` is the CD-PERSONA-0 analyzer, frozen at tag ``prereg-persona-20261106`` and
regenerated by `test_results_frozen.py`; it is not edited. This module reuses its
statistics (`wilson`, `rate`, `band`), the frozen persona-blind `scorer.py` and the
audit machinery in `audit.py`, and adds what the new registration needs.

Steps (``<dir>`` is the results directory `run.py` wrote ``arm_A.jsonl`` / ``arm_N.jsonl``
into):

    # pilot: split each arm's transcripts 80 DEV / 80 GATE for labelling (text only)
    PYTHONPATH=. python3 -m llm_rl_scripts.car_dealer_persona.analyze_current pilot-packet \\
        --dir results/persona_current_pilot_<date>
    # pilot: the scorer gate on the labelled GATE items (prints gate metrics, no cells)
    PYTHONPATH=. python3 -m llm_rl_scripts.car_dealer_persona.analyze_current gate \\
        --dir results/persona_current_pilot_<date> --arm A --labels <labels.jsonl>

    # confirmatory, after the tag: score, write the blind audit packets
    PYTHONPATH=. python3 -m llm_rl_scripts.car_dealer_persona.analyze_current packet \\
        --confirmatory --dir results/persona_current_<date>
    # after the packets are hand-labelled into <dir>/audit_labels_<arm>.jsonl
    PYTHONPATH=. python3 -m llm_rl_scripts.car_dealer_persona.analyze_current report \\
        --confirmatory --dir results/persona_current_<date> \\
        --baseline results/persona_baseline2023_20261106/results.json

Measures per arm (rates exclude ``unclear``; intervals 95% Wilson unless stated):

* M1   buyer discount constraint, P(sale | H), audit-corrected; H = B-discount with a
       no-discount seller. Arm A: the buyer's own rate (the script never discounts).
* M1b  (A) buyer spec constraint, P(sale | B-spec, missing-one), audit-corrected.
* M2   (N) P(discount offered | no-discount seller); (A) the harness assertion.
* M3   compatibility gaps, as in CD-PERSONA-0.
* M4   (A) over-budget share among priced sales at multiplier 1.25, and sale and
       over-budget rates by multiplier; (N) as in CD-PERSONA-0.
* M5   (A) decision token vs dialogue outcome, timeout and malformed shares;
       (N) the 2023 self-report measure.
* M6   (A) B-discount x S-discount: cumulative and per-offer acceptance by discount level.
* decomposition: eps_2023 - eps_N (model effect, old protocol) and eps_N - eps_A
  (protocol effect, new model), interval from the bootstrap standard errors.
"""

