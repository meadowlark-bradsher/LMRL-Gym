PILOT_DEV, PILOT_GATE = 80, 80
PILOT_SPLIT_SEED = 20261108
AUDIT_SEED = au.AUDIT_SEED
N_SPEC_SALE, N_SPEC_NO_SALE = 60, 30
TOKEN_AGREEMENT_MIN = 0.95
TIMEOUT_MAX = 0.10
DECOMP_MIN = 0.05
M6_MIN = 0.50
BASELINE_EPS = 0.198  # CD-PERSONA-0's audit-corrected M1 point estimate, as registered in P2
OFFER_TURNS = {"0%": 1, "5%": 2, "10%": 3, "15%": 4, "close": 5}


# -- rows -----------------------------------------------------------------------------
def build_rows(results: List[dict], arm: str) -> List[dict]:
    """Score each generated conversation with the frozen persona-blind scorer and attach
    the planted persona, the Arm A factors and the harness's own channels."""
    rows = []
    for res in results:
        rec = res["record"]
        if rec["arm"] != arm:
            raise ValueError(f"record {rec['id']} is arm {rec['arm']}, expected {arm}")
        text = res["text"] if arm == "A" else res["original_conversation"]
        x = s.score(text) if not res.get("refusal") else \
            {"outcome": "unclear", "price": None, "discount_offered": False, "self_report": None}
        row = {
            "id": rec["id"], "arm": arm, "buyer": rec["buyer"], "seller": rec["seller"],
            "budget": rec["budget"], "refusal": bool(res.get("refusal")),
            "outcome": x["outcome"], "price": x["price"], "discount": x["discount_offered"],
            "self_report": x["self_report"],
            "hard": rec["buyer"] == "B-discount" and rec["seller"] in NO_DISCOUNT_SELLERS,
            "hard_spec": arm == "A" and rec["buyer"] == "B-spec" and rec["feature_match"] == "missing-one",
            "text": text,
        }
        if arm == "A":
            row.update({
                "multiplier": rec["multiplier"], "feature_match": rec["feature_match"],
                "list_price": rec["list_price"],
                "token_outcome": res["token_outcome"], "sale_price": res["sale_price"],
                "buyer_price": res["buyer_price"], "n_seller_turns": res["n_seller_turns"],
                "malformed_replies": res["malformed_replies"], "seller_ok": res["seller_ok"],
            })
        rows.append(row)
    return rows


def _sale_rate(rows: List[dict]) -> dict:
    decided = [r for r in rows if r["outcome"] != "unclear"]
    k = sum(r["outcome"] == "sale" for r in decided)
    u = len(rows) - len(decided)
    out = rate(k, len(decided))
    out["unclear"] = u
    out["bounds_unclear"] = ([k / len(rows), (k + u) / len(rows)] if rows else [float("nan")] * 2)
    return out


def _gap(cells: Dict[str, dict], b: str) -> dict:
    comp = cells[COMPATIBLE[b]]
    others = [cells[sel] for sel in SELLERS if sel != COMPATIBLE[b]]
    gap = comp["rate"] - sum(o["rate"] for o in others) / 2
    var = comp["rate"] * (1 - comp["rate"]) / comp["n"] if comp["n"] else float("nan")
    var += sum(o["rate"] * (1 - o["rate"]) / o["n"] if o["n"] else float("nan") for o in others) / 4
    se = sqrt(var) if var == var and var >= 0 else float("nan")
    return {"compatible_seller": COMPATIBLE[b], "gap": gap, "ci95": [gap - 1.96 * se, gap + 1.96 * se]}


# -- measures -------------------------------------------------------------------------
def measures(rows: List[dict], arm: str) -> dict:
    live = [r for r in rows if not r["refusal"]]
    m: dict = {"arm": arm, "n": len(rows), "refusals": len(rows) - len(live),
               "unclear": sum(r["outcome"] == "unclear" for r in live)}

    hard = [r for r in live if r["hard"]]
    m1 = _sale_rate(hard)
    m1.update(band(m1["rate"], m1["ci95"]))
    m1["by_seller"] = {sel: _sale_rate([r for r in hard if r["seller"] == sel]) for sel in NO_DISCOUNT_SELLERS}
    m["M1_cell"] = m1

    cells = {b: {sel: _sale_rate([r for r in live if r["buyer"] == b and r["seller"] == sel])
                 for sel in SELLERS} for b in BUYERS}
    m["M3"] = {"cells": cells, "gaps": {b: _gap(cells[b], b) for b in BUYERS}}

    if arm == "N":
        nd = [r for r in live if r["seller"] in NO_DISCOUNT_SELLERS]
        m2 = rate(sum(r["discount"] for r in nd), len(nd))
        m2.update(band(m2["rate"], m2["ci95"]))
        m2["by_seller"] = {sel: rate(sum(r["discount"] for r in nd if r["seller"] == sel),
                                     sum(r["seller"] == sel for r in nd)) for sel in NO_DISCOUNT_SELLERS}
        m["M2"] = m2
        m["M1_text"] = _sale_rate([r for r in live if r["buyer"] == "B-discount" and not r["discount"]])
        priced = [r for r in live if r["outcome"] == "sale" and r["price"] is not None]
        m4 = rate(sum(r["price"] > r["budget"] for r in priced), len(priced))
        m4["sales_without_price"] = sum(r["outcome"] == "sale" and r["price"] is None for r in live)
        m4["by_budget"] = {str(b): rate(sum(r["price"] > r["budget"] for r in priced if r["budget"] == b),
                                        sum(r["budget"] == b for r in priced))
                           for b in sorted({r["budget"] for r in live})}
        m["M4"] = m4
        decided = [r for r in live if r["outcome"] != "unclear"]
        clean = [r for r in decided if r["self_report"] in (0.0, 1.0)]
        m5 = rate(sum((r["outcome"] == "sale") == (r["self_report"] == 1.0) for r in clean), len(clean))
        frac = [r for r in live if r["self_report"] is not None and 0.0 < r["self_report"] < 1.0]
        m5["fractional"] = {"n": len(frac),
                            **{o: sum(r["outcome"] == o for r in frac) for o in ("sale", "no_sale", "unclear")}}
        m5["no_self_report"] = sum(r["self_report"] is None for r in live)
        m["M5"] = m5
        return m

    # Arm A
    spec = [r for r in live if r["hard_spec"]]
    m1b = _sale_rate(spec)
    m1b.update(band(m1b["rate"], m1b["ci95"]))
    m1b["all_features"] = _sale_rate([r for r in live if r["buyer"] == "B-spec" and r["feature_match"] == "all"])
    m["M1b_cell"] = m1b

    m["M2"] = {"by_construction": True,
               "seller_ok_all": all(r["seller_ok"] for r in rows),
               "seller_violations": sum(not r["seller_ok"] for r in rows)}

    mults = sorted({r["multiplier"] for r in live})
    priced = [r for r in live if r["outcome"] == "sale" and r["price"] is not None]
    over = [r for r in priced if r["multiplier"] == 1.25]
    m4 = rate(sum(r["price"] > r["budget"] for r in over), len(over))
    m4["sales_without_price"] = sum(r["outcome"] == "sale" and r["price"] is None for r in live)
    m4["price_matches_close"] = rate(sum(r["sale_price"] is not None and r["price"] == r["sale_price"] for r in priced),
                                     len(priced))
    m4["by_multiplier"] = {str(mu): {"sale": _sale_rate([r for r in live if r["multiplier"] == mu]),
                                     "over_budget": rate(sum(r["price"] > r["budget"] for r in priced if r["multiplier"] == mu),
                                                         sum(r["multiplier"] == mu for r in priced))}
                           for mu in mults}
    m["M4"] = m4

    decided = [r for r in live if r["outcome"] != "unclear" and r["token_outcome"] in ("sale", "no_sale", "timeout")]
    m5 = rate(sum((r["outcome"] == "sale") == (r["token_outcome"] == "sale") for r in decided), len(decided))
    m5["timeout"] = rate(sum(r["token_outcome"] == "timeout" for r in live), len(live))
    n_replies = sum(min(r["n_seller_turns"], 5) for r in live)
    m5["malformed_replies"] = rate(sum(r["malformed_replies"] for r in live), n_replies)
    m5["disagreements"] = [{"id": r["id"], "scorer": r["outcome"], "token": r["token_outcome"]}
                           for r in decided if (r["outcome"] == "sale") != (r["token_outcome"] == "sale")]
    m["M5"] = m5

    dd = [r for r in live if r["buyer"] == "B-discount" and r["seller"] == "S-discount"]
    bought_at = {}
    for r in dd:
        if r["token_outcome"] == "sale":
            bought_at[r["n_seller_turns"]] = bought_at.get(r["n_seller_turns"], 0) + 1
    cumulative, per_offer = {}, {}
    for name, t in OFFER_TURNS.items():
        k = sum(v for turn, v in bought_at.items() if turn <= t)
        cumulative[name] = rate(k, len(dd))
        still_in = len(dd) - sum(v for turn, v in bought_at.items() if turn < t) \
            - sum(r["token_outcome"] == "no_sale" and r["n_seller_turns"] < t for r in dd)
        per_offer[name] = rate(bought_at.get(t, 0), still_in)
    m["M6"] = {"n": len(dd), "cumulative": cumulative, "per_offer": per_offer,
               "left_without_buying": rate(sum(r["token_outcome"] == "no_sale" for r in dd), len(dd))}
    return m


# -- the 2x2 decomposition ------------------------------------------------------------
def _se(ci: List[float]) -> float:
    return (ci[1] - ci[0]) / 3.92


def decomposition(eps_2023: dict, eps_n: dict, eps_a: dict) -> dict:
    """``eps_*``: ``{"rate", "ci95"}``. Differences with normal intervals built from each
    estimate's bootstrap (or Wilson) standard error."""
    def diff(x: dict, y: dict, name: str) -> dict:
        d = x["rate"] - y["rate"]
        se = sqrt(_se(x["ci95"]) ** 2 + _se(y["ci95"]) ** 2)
        return {"name": name, "diff": d, "ci95": [d - 1.96 * se, d + 1.96 * se]}
    return {"cells": {"2023_narrator": eps_2023, "current_narrator": eps_n, "current_agent": eps_a},
            "model_effect": diff(eps_2023, eps_n, "eps_2023 - eps_N (old protocol, model swapped)"),
            "protocol_effect": diff(eps_n, eps_a, "eps_N - eps_A (new model, protocol swapped)")}


# -- predictions ----------------------------------------------------------------------
def predictions(mA: dict, mN: dict, auditA: dict, auditN: dict, audit_spec: dict, decomp: dict) -> dict:
    def verdict(ok: bool) -> str:
        return "CONFIRMED" if ok else "REFUTED"

    by_seller = {sel: mA["M1_cell"]["by_seller"][sel]["rate"] for sel in NO_DISCOUNT_SELLERS}
    gaps = {arm: {b: m["M3"]["gaps"][b]["gap"] for b in BUYERS} for arm, m in (("A", mA), ("N", mN))}
    m6 = mA["M6"]["cumulative"]
    seq = [m6[k]["rate"] for k in ("0%", "5%", "10%", "15%")]
    return {
        "P1": {"claim": f"Arm A: eps_buyer HELD (<= {HELD_MAX}) with S-concise, > {HELD_MAX} with S-features (raw by seller)",
               "value": by_seller, "pooled_audit_corrected": auditA["corrected_rate"],
               "verdict": verdict(by_seller["S-concise"] <= HELD_MAX and by_seller["S-features"] > HELD_MAX)},
        "P2": {"claim": f"Arm N: eps_buyer > {HELD_MAX} and <= {BASELINE_EPS} (2023)",
               "value": auditN["corrected_rate"],
               "verdict": verdict(HELD_MAX < auditN["corrected_rate"] <= BASELINE_EPS)},
        "P3": {"claim": f"eps_N - eps_A >= {DECOMP_MIN}", "value": decomp["protocol_effect"]["diff"],
               "verdict": verdict(decomp["protocol_effect"]["diff"] >= DECOMP_MIN)},
        "P4": {"claim": "B-impatient compatibility gap < 0 in both arms",
               "value": {arm: gaps[arm]["B-impatient"] for arm in ("A", "N")},
               "verdict": verdict(gaps["A"]["B-impatient"] < 0 and gaps["N"]["B-impatient"] < 0)},
        "P5": {"claim": f"eps_spec > {HELD_MAX}", "value": audit_spec["corrected_rate"],
               "verdict": verdict(audit_spec["corrected_rate"] > HELD_MAX)},
        "P6": {"claim": f"token agrees with dialogue >= {TOKEN_AGREEMENT_MIN}; timeout share < {TIMEOUT_MAX}",
               "value": {"agreement": mA["M5"]["rate"], "timeout": mA["M5"]["timeout"]["rate"]},
               "verdict": verdict(mA["M5"]["rate"] >= TOKEN_AGREEMENT_MIN and mA["M5"]["timeout"]["rate"] < TIMEOUT_MAX)},
        "P7": {"claim": f"M6 cumulative acceptance non-decreasing in the offer and >= {M6_MIN} after 15%",
               "value": {k: m6[k]["rate"] for k in ("0%", "5%", "10%", "15%")},
               "verdict": verdict(all(a <= b for a, b in zip(seq, seq[1:])) and seq[-1] >= M6_MIN)},
        "P8": {"claim": "void: no second buyer registered", "verdict": "VOID"},
        "gap_detail": gaps,
    }


# -- audit packets --------------------------------------------------------------------
def build_packet(rows: List[dict], arm: str, seed: int = AUDIT_SEED) -> Dict[str, list]:
    """The CD-PERSONA-0 packet for H (60 + 30 plus decoys to 180), and for Arm A a further
    60 scorer-sales and 30 scorer-no-sales from H_spec not already in the packet; all
    shuffled together. The key holds stratum and scorer call; the packet only text."""
    live = [r for r in rows if not r["refusal"]]
    built = au.build_packet(live, seed=seed)
    items = [{"row": next(r for r in live if r["id"] == k["id"]), "stratum": k["stratum"]}
             for k in built["key"]]
    if arm == "A":
        rng = random.Random(seed + 1)
        used = {it["row"]["id"] for it in items}
        for outcome, n, tag in (("sale", N_SPEC_SALE, "spec_sale"), ("no_sale", N_SPEC_NO_SALE, "spec_no_sale")):
            pool = sorted((r for r in live if r["hard_spec"] and r["outcome"] == outcome and r["id"] not in used),
                          key=lambda r: r["id"])
            rng.shuffle(pool)
            items += [{"row": r, "stratum": tag} for r in pool[:n]]
        rng.shuffle(items)
    packet = [{"item": i, "text": it["row"]["text"]} for i, it in enumerate(items)]
    key = [{"item": i, "id": it["row"]["id"], "stratum": it["stratum"],
            "scorer_outcome": it["row"]["outcome"]} for i, it in enumerate(items)]
    return {"packet": packet, "key": key}


def _spec_key(key: List[dict]) -> List[dict]:
    """The H_spec strata of a key, renamed so `audit.corrected_rate` reads them as H."""
    rename = {"spec_sale": "hard_sale", "spec_no_sale": "hard_no_sale"}
    return [{**k, "stratum": rename[k["stratum"]]} for k in key if k["stratum"] in rename]


def _counts(rows: List[dict], flag: str) -> Tuple[int, int]:
    cell = [r for r in rows if r[flag] and not r["refusal"]]
    return (sum(r["outcome"] == "sale" for r in cell), sum(r["outcome"] == "no_sale" for r in cell))


def corrected(rows: List[dict], key: List[dict], labels: Dict[int, str], arm: str) -> dict:
    """Audit-corrected M1 for the arm, and for Arm A also M1b, each with the
    unclear-as-sale sensitivity."""
    missing = [k["item"] for k in key if k["item"] not in labels]
    if missing:
        raise ValueError(f"{len(missing)} audit items are unlabelled, e.g. {missing[:5]}")
    out = {}
    S, N = _counts(rows, "hard")
    main_key = [k for k in key if not k["stratum"].startswith("spec_")]
    main_labels = {k["item"]: labels[k["item"]] for k in main_key}
    out["M1"] = au.corrected_rate(S, N, main_key, main_labels)
    out["M1_unclear_as_sale"] = au.corrected_rate(S, N, main_key, main_labels, unclear_as_sale=True)
    if arm == "A":
        S, N = _counts(rows, "hard_spec")
        spec_key = _spec_key(key)
        spec_labels = {k["item"]: labels[k["item"]] for k in spec_key}
        out["M1b"] = au.corrected_rate(S, N, spec_key, spec_labels)
        out["M1b_unclear_as_sale"] = au.corrected_rate(S, N, spec_key, spec_labels, unclear_as_sale=True)
    return out


# -- pilot ----------------------------------------------------------------------------
def pilot_split(rows: List[dict], seed: int = PILOT_SPLIT_SEED) -> Dict[str, List[dict]]:
    """DEV / GATE halves of a pilot arm, by id, deterministic. Text only."""
    ids = sorted(r["id"] for r in rows)
    random.Random(seed).shuffle(ids)
    by_id = {r["id"]: r for r in rows}
    dev, gate = ids[:PILOT_DEV], ids[PILOT_DEV:PILOT_DEV + PILOT_GATE]
    return {name: [{"index": i, "id": rid, "original_conversation": by_id[rid]["text"]}
                   for i, rid in enumerate(chosen)] for name, chosen in (("dev", dev), ("gate", gate))}


def gate(rows: List[dict], labels: List[dict]) -> dict:
    """The registered scorer gate on labelled pilot items (`validate.validate`), with the
    conversation text taken from ``rows`` by id. Labels: ``{id, outcome, discount_offered,
    price}``."""
    by_id = {r["id"]: r for r in rows}
    gold = [{"index": i, "id": lab["id"], "original_conversation": by_id[lab["id"]]["text"],
             "outcome": lab["outcome"], "discount_offered": bool(lab.get("discount_offered", False)),
             "price": lab.get("price")} for i, lab in enumerate(labels)]
    return va.validate(gold)


# -- io and CLI -----------------------------------------------------------------------
def load_results(path: str) -> List[dict]:
    with open(path) as f:
        return [json.loads(line) for line in f if line.strip()]


def _write_jsonl(items: List[dict], path: str) -> None:
    with open(path, "w") as f:
        for it in items:
            f.write(json.dumps(it) + "\n")


def analyze(rowsA: List[dict], rowsN: List[dict], auditA: dict, auditN: dict, baseline: dict) -> dict:
    mA, mN = measures(rowsA, "A"), measures(rowsN, "N")
    eps_2023 = {"rate": baseline["audit"]["corrected_rate"], "ci95": baseline["audit"]["ci95"]}
    eps_n = {"rate": auditN["M1"]["corrected_rate"], "ci95": auditN["M1"]["ci95"]}
    eps_a = {"rate": auditA["M1"]["corrected_rate"], "ci95": auditA["M1"]["ci95"]}
    decomp = decomposition(eps_2023, eps_n, eps_a)
    out = {"A": mA, "N": mN, "audit": {"A": auditA, "N": auditN}, "decomposition": decomp,
           "M1_verdict": {arm: {"corrected_rate": a["M1"]["corrected_rate"], "ci95": a["M1"]["ci95"],
                                **band(a["M1"]["corrected_rate"], a["M1"]["ci95"])}
                          for arm, a in (("A", auditA), ("N", auditN))},
           "M1b_verdict": {"corrected_rate": auditA["M1b"]["corrected_rate"], "ci95": auditA["M1b"]["ci95"],
                           **band(auditA["M1b"]["corrected_rate"], auditA["M1b"]["ci95"])}}
    out["predictions"] = predictions(mA, mN, auditA["M1"], auditN["M1"], auditA["M1b"], decomp)
    return out


def _print_report(r: dict) -> None:
    def fmt(x: dict) -> str:
        return f"{x['rate']:.3f} [{x['ci95'][0]:.3f}, {x['ci95'][1]:.3f}] ({x['k']}/{x['n']})"

    for arm in ARMS:
        m, v = r[arm], r["M1_verdict"][arm]
        print(f"Arm {arm}: n = {m['n']}, refusals {m['refusals']}, scorer unclear {m['unclear']}")
        print(f"  M1 raw {fmt(m['M1_cell'])}  corrected {v['corrected_rate']:.3f} "
              f"[{v['ci95'][0]:.3f}, {v['ci95'][1]:.3f}] {v['band']}{' (borderline)' if v['borderline'] else ''}")
        for sel in NO_DISCOUNT_SELLERS:
            print(f"     with {sel}: {fmt(m['M1_cell']['by_seller'][sel])}")
        for b in BUYERS:
            g = m["M3"]["gaps"][b]
            print(f"  M3 gap {b:12s} {g['gap']:+.3f} [{g['ci95'][0]:+.3f}, {g['ci95'][1]:+.3f}]")
    a, vb = r["A"], r["M1b_verdict"]
    print(f"  M1b raw {fmt(a['M1b_cell'])}  corrected {vb['corrected_rate']:.3f} {vb['band']}")
    print(f"  M2 (A) seller lines verified: {a['M2']['seller_ok_all']}; (N) {fmt(r['N']['M2'])}")
    print(f"  M4 (A) over budget at 1.25: {fmt(a['M4'])}; (N) {fmt(r['N']['M4'])}")
    print(f"  M5 (A) token agreement {fmt(a['M5'])}, timeout {fmt(a['M5']['timeout'])}; "
          f"(N) self-report {fmt(r['N']['M5'])}")
    print("  M6 cumulative: " + ", ".join(f"{k} {v['rate']:.2f}" for k, v in a["M6"]["cumulative"].items()))
    for k in ("model_effect", "protocol_effect"):
        d = r["decomposition"][k]
        print(f"  {d['name']}: {d['diff']:+.3f} [{d['ci95'][0]:+.3f}, {d['ci95'][1]:+.3f}]")
    for name, pr in r["predictions"].items():
        if name.startswith("P"):
            print(f"{name}: {pr['verdict']:9s} {pr['claim']}  (value: {pr.get('value')})")


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("step", choices=("pilot-packet", "gate", "packet", "report"))
    p.add_argument("--dir", required=True, help="directory with arm_A.jsonl / arm_N.jsonl")
    p.add_argument("--arm", choices=ARMS, help="for gate")
    p.add_argument("--labels", help="for gate: labelled pilot GATE items")
    p.add_argument("--confirmatory", action="store_true",
                   help="required for packet/report: the registration is frozen")
    p.add_argument("--baseline", default="results/persona_baseline2023_20261106/results.json")
    args = p.parse_args(argv)

    def rows_for(arm: str) -> List[dict]:
        return build_rows(load_results(os.path.join(args.dir, f"arm_{arm}.jsonl")), arm)

    if args.step == "pilot-packet":
        for arm in ARMS:
            path = os.path.join(args.dir, f"arm_{arm}.jsonl")
            if not os.path.exists(path):
                continue
            split = pilot_split(rows_for(arm))
            for name, items in split.items():
                _write_jsonl(items, os.path.join(args.dir, f"pilot_{name}_{arm}.jsonl"))
            print(f"arm {arm}: wrote {len(split['dev'])} dev and {len(split['gate'])} gate items (text only)")
        return 0

    if args.step == "gate":
        if not (args.arm and args.labels):
            p.error("gate needs --arm and --labels")
        labels = load_results(args.labels)
        g = gate(rows_for(args.arm), labels)
        with open(os.path.join(args.dir, f"gate_{args.arm}.json"), "w") as f:
            json.dump(g, f, indent=1)
        print(f"arm {args.arm}: n={g['n']} accuracy={g['accuracy']:.3f} unclear={g['scorer_unclear_rate']:.3f} "
              f"false_sales={g['false_sales']}/{g['n_labelled_no_sale']} missed={g['missed_sales']}/{g['n_labelled_sale']} "
              f"discount={g['discount_agreement']:.3f} sale_gate={'PASS' if g['sale_gate'] else 'FAIL'} "
              f"discount_gate={'PASS' if g['discount_gate'] else 'FAIL'}")
        return 0

    if not args.confirmatory:
        print("refusing to tabulate the confirmatory arms without --confirmatory "
              "(pass it only after the registration is frozen)", file=sys.stderr)
        return 2

    if args.step == "packet":
        for arm in ARMS:
            rows = rows_for(arm)
            built = build_packet(rows, arm)
            au.write_packet(built, os.path.join(args.dir, f"audit_packet_{arm}.jsonl"),
                            os.path.join(args.dir, f"audit_key_{arm}.json"))
            _write_jsonl([{k: v for k, v in r.items() if k != "text"} for r in rows],
                         os.path.join(args.dir, f"scores_{arm}.jsonl"))
            # deliberately prints no outcome counts: the labeler must stay blind
            print(f"arm {arm}: wrote {len(built['packet'])} audit items; label them into "
                  f"audit_labels_{arm}.jsonl before opening the key or scores")
        return 0

    rowsA, rowsN = rows_for("A"), rows_for("N")
    audits = {}
    for arm, rows in (("A", rowsA), ("N", rowsN)):
        with open(os.path.join(args.dir, f"audit_key_{arm}.json")) as f:
            key = json.load(f)
        labels = au.load_labels(os.path.join(args.dir, f"audit_labels_{arm}.jsonl"))
        audits[arm] = corrected(rows, key, labels, arm)
    with open(args.baseline) as f:
        baseline = json.load(f)
    result = analyze(rowsA, rowsN, audits["A"], audits["N"], baseline)
    with open(os.path.join(args.dir, "results.json"), "w") as f:
        json.dump(result, f, indent=1)
    _print_report(result)
    return 0


if __name__ == "__main__":
    sys.exit(main())
