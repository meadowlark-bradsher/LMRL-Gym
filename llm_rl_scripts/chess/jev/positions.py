"""P1 stimuli: build a stratified, deduplicated set of FEN snapshots.

Positions are generated by self-play so the set is fully reproducible from a
seed and needs no external dataset. To keep games plausible (not random-walk
junk) the mover is Stockfish with ``MultiPV``; among the top replies one is
picked with a seeded weighting, which diversifies lines without wandering into
nonsense. Positions are sampled across four phases:

    opening | middlegame | tactical | endgame

"tactical" here means a position with a genuine decision -- the best legal move
is much better than the rest (a large best-vs-second-best centipawn gap), or a
forced mate is available. Those are the positions where move quality is actually
measurable; in quiet positions every legal move scores alike and no selector can
be told apart. Phase is otherwise decided by fullmove number and material.

Each record is written to ``positions.jsonl`` with provenance so a separate
analyst can reconstruct it:

    position_id, fen, phase, tactic_type, side_to_move, fullmove, piece_count,
    source_game, source_ply, best_gap_cp, best_is_mate, generator

Usage (offline; needs a Stockfish binary, no API):
    conda run --no-capture-output -n LLM_RL python -u \
        -m llm_rl_scripts.chess.jev.positions --out positions.jsonl \
        --count 200 --seed 0 --engine-path /opt/homebrew/bin/stockfish
"""

from __future__ import annotations

import argparse
import json
import random
import shutil
from dataclasses import asdict, dataclass
from typing import Dict, List, Optional

import chess
import chess.engine

PHASES = ("opening", "middlegame", "tactical", "endgame")
DEFAULT_SPLIT = {"opening": 40, "middlegame": 60, "tactical": 60, "endgame": 40}

# A decision is "tactical" when the best move beats the second-best by at least
# this many centipawns (or a forced mate exists).
TACTICAL_GAP_CP = 150


@dataclass
class Position:
    position_id: str
    fen: str
    phase: str
    tactic_type: Optional[str]      # "forced_mate" | "critical_gap" | None
    side_to_move: str               # "white" | "black"
    fullmove: int
    piece_count: int
    source_game: int
    source_ply: int
    best_gap_cp: Optional[int]
    best_is_mate: bool
    generator: str


def _piece_count(board: chess.Board) -> int:
    return chess.popcount(board.occupied)


def _phase_of(board: chess.Board) -> str:
    """Coarse phase from material and move number (tactical is decided later)."""
    pc = _piece_count(board)
    if pc <= 10:
        return "endgame"
    if board.fullmove_number <= 8:
        return "opening"
    return "middlegame"


def _score_cp(score: chess.engine.PovScore, pov: chess.Color) -> Optional[int]:
    """White/Black-relative centipawns; mate scores mapped to a large magnitude."""
    s = score.pov(pov)
    if s.is_mate():
        m = s.mate()
        return 100000 - abs(m) * 100 if m is not None and m > 0 else -100000 + abs(m or 0) * 100
    return s.score()


def _analyse_multipv(engine, board, depth, k):
    return engine.analyse(board, chess.engine.Limit(depth=depth), multipv=k)


# Canonical endgame material (White to move, White is the agent). Each entry is
# (white_pieces, black_pieces) as piece-type lists excluding the kings.
_ENDGAME_MATERIAL = [
    ([chess.QUEEN], []),                         # KQ vs K
    ([chess.ROOK], []),                          # KR vs K
    ([chess.ROOK], [chess.ROOK]),                # KR vs KR
    ([chess.QUEEN], [chess.ROOK]),               # KQ vs KR
    ([chess.PAWN], []),                          # KP vs K
    ([chess.BISHOP, chess.BISHOP], []),          # KBB vs K
    ([chess.KNIGHT, chess.BISHOP], []),          # KNB vs K
    ([chess.ROOK, chess.PAWN], [chess.ROOK]),    # KRP vs KR
]


def _random_endgame(rng: random.Random) -> Optional[str]:
    """Construct a legal, not-yet-over endgame FEN with White to move."""
    white_extra, black_extra = rng.choice(_ENDGAME_MATERIAL)
    for _ in range(200):
        board = chess.Board.empty()
        squares = rng.sample(range(64), 2 + len(white_extra) + len(black_extra))
        wk, bk = squares[0], squares[1]
        if chess.square_distance(wk, bk) <= 1:  # kings can't be adjacent
            continue
        board.set_piece_at(wk, chess.Piece(chess.KING, chess.WHITE))
        board.set_piece_at(bk, chess.Piece(chess.KING, chess.BLACK))
        ok = True
        idx = 2
        for pt in white_extra:
            sq = squares[idx]; idx += 1
            if pt == chess.PAWN and chess.square_rank(sq) in (0, 7):
                ok = False; break
            board.set_piece_at(sq, chess.Piece(pt, chess.WHITE))
        for pt in black_extra:
            sq = squares[idx]; idx += 1
            if pt == chess.PAWN and chess.square_rank(sq) in (0, 7):
                ok = False; break
            board.set_piece_at(sq, chess.Piece(pt, chess.BLACK))
        if not ok:
            continue
        board.turn = chess.WHITE
        if board.is_valid() and not board.is_game_over() and list(board.legal_moves):
            return board.fen()
    return None


def generate(
    engine_path: str,
    count: int,
    seed: int,
    split: Dict[str, int],
    gen_depth: int = 8,
    multipv: int = 4,
    max_games: int = 80,
    max_plies: int = 70,
) -> List[Position]:
    rng = random.Random(seed)
    engine = chess.engine.SimpleEngine.popen_uci(engine_path)
    want = dict(split)
    buckets: Dict[str, List[Position]] = {p: [] for p in PHASES}
    seen_fens = set()
    gid = 0
    try:
        # Endgame bucket: constructed positions (self-play rarely reaches them).
        for _ in range(want.get("endgame", 0) * 20):
            if len(buckets["endgame"]) >= want.get("endgame", 0):
                break
            fen = _random_endgame(rng)
            if fen is None:
                continue
            key = " ".join(fen.split(" ")[:4])
            if key in seen_fens:
                continue
            board = chess.Board(fen)
            infos = _analyse_multipv(engine, board, gen_depth, multipv)
            pov = board.turn
            scores = [_score_cp(i["score"], pov) for i in infos if i.get("pv")]
            best = scores[0] if scores else 0
            second = scores[1] if len(scores) > 1 else best
            gap = int((best or 0) - (second or 0))
            best_is_mate = infos[0]["score"].pov(pov).is_mate() and (infos[0]["score"].pov(pov).mate() or 0) > 0
            pid = "endgame_{:04d}".format(len(buckets["endgame"]))
            buckets["endgame"].append(Position(
                position_id=pid, fen=fen, phase="endgame",
                tactic_type="forced_mate" if best_is_mate else None,
                side_to_move="white", fullmove=board.fullmove_number,
                piece_count=_piece_count(board), source_game=-1, source_ply=0,
                best_gap_cp=gap, best_is_mate=bool(best_is_mate),
                generator="constructed-endgame"))
            seen_fens.add(key)

        # Opening / middlegame / tactical buckets: self-play.
        nonend = count - len(buckets["endgame"])
        while sum(len(buckets[p]) for p in PHASES if p != "endgame") < nonend and gid < max_games:
            board = chess.Board()
            for ply in range(max_plies):
                if board.is_game_over():
                    break
                infos = _analyse_multipv(engine, board, gen_depth, multipv)
                if not infos:
                    break
                pov = board.turn
                moves, scores = [], []
                for info in infos:
                    pv = info.get("pv")
                    if not pv:
                        continue
                    moves.append(pv[0])
                    scores.append(_score_cp(info["score"], pov))

                # Decide whether to *sample* this position before advancing.
                fen = board.fen()
                key = " ".join(fen.split(" ")[:4])  # ignore move clocks for dedup
                if key not in seen_fens and len(moves) >= 1:
                    best = scores[0] if scores[0] is not None else 0
                    second = scores[1] if len(scores) > 1 and scores[1] is not None else best
                    gap = int(best - second)
                    best_is_mate = infos[0]["score"].pov(pov).is_mate() and (infos[0]["score"].pov(pov).mate() or 0) > 0
                    tactic = "forced_mate" if best_is_mate else ("critical_gap" if gap >= TACTICAL_GAP_CP else None)
                    phase = "tactical" if tactic else _phase_of(board)
                    if want.get(phase, 0) > len(buckets[phase]):
                        pid = "{}_{:04d}".format(phase, len(buckets[phase]))
                        buckets[phase].append(Position(
                            position_id=pid, fen=fen, phase=phase, tactic_type=tactic,
                            side_to_move="white" if board.turn == chess.WHITE else "black",
                            fullmove=board.fullmove_number, piece_count=_piece_count(board),
                            source_game=gid, source_ply=ply, best_gap_cp=gap,
                            best_is_mate=bool(best_is_mate),
                            generator="selfplay-sf-d{}-mpv{}".format(gen_depth, multipv),
                        ))
                        seen_fens.add(key)

                # Advance the game: pick among the top MultiPV moves, seeded, so
                # lines diversify but stay plausible (weight toward the best).
                weights = [max(1, len(moves) - i) for i in range(len(moves))]
                board.push(rng.choices(moves, weights=weights, k=1)[0])
            gid += 1
    finally:
        engine.quit()

    out: List[Position] = []
    for p in PHASES:
        out.extend(buckets[p])
    return out


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--out", required=True)
    p.add_argument("--count", type=int, default=200)
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--engine-path", default=None)
    p.add_argument("--gen-depth", type=int, default=8)
    p.add_argument("--multipv", type=int, default=4)
    p.add_argument("--max-games", type=int, default=120)
    args = p.parse_args()

    engine_path = args.engine_path or shutil.which("stockfish")
    if not engine_path:
        raise SystemExit("no Stockfish binary; pass --engine-path")

    split = dict(DEFAULT_SPLIT)
    # Scale the default 40/60/60/40 split to the requested count.
    total = sum(split.values())
    if args.count != total:
        split = {k: max(1, round(v * args.count / total)) for k, v in split.items()}

    positions = generate(engine_path, args.count, args.seed, split,
                         gen_depth=args.gen_depth, multipv=args.multipv,
                         max_games=args.max_games)
    with open(args.out, "w") as f:
        for pos in positions:
            f.write(json.dumps(asdict(pos)) + "\n")

    by_phase: Dict[str, int] = {}
    for pos in positions:
        by_phase[pos.phase] = by_phase.get(pos.phase, 0) + 1
    print("wrote {} positions to {}".format(len(positions), args.out))
    for phase in PHASES:
        print("  {:<12s} {}".format(phase, by_phase.get(phase, 0)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
