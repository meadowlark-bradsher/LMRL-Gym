"""Exact expected-payoff evaluation of a policy, with answer-kernel mismatch.

A policy acts on the belief it *thinks* it holds, but answers are generated by the
*true* answer kernel. When the two kernels agree these coincide and evaluation is the
ordinary belief-MDP value; when they differ (the agent assumes truthful answers but
the buyer is noisy or strategic) the agent's belief diverges from the truth, and it
offers a deal chosen under a belief that no longer matches who the buyer is.

So the evaluator carries *two* beliefs down the answer tree:

* ``b_as`` -- the agent's belief, updated with the policy's **assumed** kernel; the
  policy chooses its action from this.
* ``b_tr`` -- the true posterior over types, updated with the **eval** kernel; answer
  probabilities and the realised acceptance of an offer are governed by this.

The payoff of offering deal ``d`` is ``U_focal(d) * P_true(accept d)``; each question
subtracts ``token_price * cost``. The recursion is exact (no sampling): it sums over
both answers, weighting by the true marginal. Under a matched kernel the result for
``OraclePolicy`` equals ``oracle.summarize(...)["V_star"]`` by construction.
"""

from __future__ import annotations

from typing import FrozenSet

import numpy as np

from . import game as g


def evaluate(policy, eval_kernel: g.Kernel, token_price: float) -> dict:
    """Expected payoff (and ask statistics) of ``policy`` from the uniform prior,
    with answers drawn from ``eval_kernel`` and questions charged at ``token_price``."""
    p_as = policy.assumed_pyes()          # [Q, T] the agent's model of answers
    p_ev = eval_kernel.p_yes()            # [Q, T] the answers actually given

    def rec(b_as: np.ndarray, b_tr: np.ndarray, asked: FrozenSet[int]):
        act = policy.action(b_as, asked)
        if act[0] == "OFFER":
            d = act[1]
            payoff = float(g.U_FOCAL[d] * g.accept_prob(b_tr)[d])
            return payoff, 0.0, 0.0            # (payoff, E[#questions], E[tokens])
        q = act[1]
        cost = g.BANK[q].cost
        payoff = 0.0
        e_q = 1.0
        e_tok = float(cost)
        for yes in (True, False):
            lik_ev = p_ev[q] if yes else (1.0 - p_ev[q])
            w_tr = b_tr * lik_ev
            p_obs = float(w_tr.sum())         # true probability of this answer
            if p_obs <= 0:
                continue
            b_tr2 = w_tr / p_obs
            lik_as = p_as[q] if yes else (1.0 - p_as[q])
            w_as = b_as * lik_as
            z_as = float(w_as.sum())
            b_as2 = (w_as / z_as) if z_as > 0 else b_as   # agent "surprised": keep prior
            sub_pay, sub_q, sub_tok = rec(b_as2, b_tr2, asked | {q})
            payoff += p_obs * sub_pay
            e_q += p_obs * sub_q
            e_tok += p_obs * sub_tok
        return payoff - token_price * cost, e_q, e_tok

    b0 = g.uniform()
    payoff, e_q, e_tok = rec(b0, b0, frozenset())
    first = policy.action(b0, frozenset())
    first_label = "OFFER" if first[0] == "OFFER" else g.BANK[first[1]].id
    return {"payoff": payoff, "exp_questions": e_q, "exp_tokens": e_tok,
            "first_action": first_label}
